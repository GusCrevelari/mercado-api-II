CREATE SEQUENCE CP5_SEQ_USUARIO
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE CP5_USUARIO (
    ID BIGINT NOT NULL,
    NOME VARCHAR(120) NOT NULL,
    LOGIN VARCHAR(100) NOT NULL,
    SENHA VARCHAR(100) NOT NULL,
    ATIVO BOOLEAN NOT NULL,
    PERFIL VARCHAR(20) NOT NULL,
    CONSTRAINT PK_CP5_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_CP5_USUARIO_LOGIN UNIQUE (LOGIN),
    CONSTRAINT CK_CP5_USUARIO_PERFIL CHECK (PERFIL IN ('ADMIN', 'CLIENTE'))
);
