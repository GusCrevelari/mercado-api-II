ALTER TABLE CP5_USUARIO
    ADD COLUMN EMAIL VARCHAR(254);

CREATE UNIQUE INDEX UK_CP5_USUARIO_EMAIL
    ON CP5_USUARIO (EMAIL);

CREATE SEQUENCE CP5_SEQ_PAYMENT_OUTBOX
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE CP5_PAYMENT_OUTBOX (
    ID BIGINT NOT NULL,
    COMPRA_ID BIGINT NOT NULL,
    PAYMENT_ATTEMPT_ID UUID NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    TENTATIVAS INTEGER NOT NULL DEFAULT 0,
    CRIADO_EM TIMESTAMP WITH TIME ZONE NOT NULL,
    ULTIMA_TENTATIVA_EM TIMESTAMP WITH TIME ZONE,
    PUBLICADO_EM TIMESTAMP WITH TIME ZONE,
    ULTIMO_ERRO VARCHAR(1000),
    CONSTRAINT PK_CP5_PAYMENT_OUTBOX PRIMARY KEY (ID),
    CONSTRAINT FK_CP5_PAYMENT_OUTBOX_COMPRA FOREIGN KEY (COMPRA_ID)
        REFERENCES CP5_COMPRA (ID) ON DELETE CASCADE,
    CONSTRAINT UK_CP5_PAYMENT_OUTBOX_COMPRA UNIQUE (COMPRA_ID),
    CONSTRAINT UK_CP5_PAYMENT_OUTBOX_ATTEMPT UNIQUE (PAYMENT_ATTEMPT_ID),
    CONSTRAINT CK_CP5_PAYMENT_OUTBOX_STATUS CHECK (STATUS IN ('PENDING', 'PUBLISHED')),
    CONSTRAINT CK_CP5_PAYMENT_OUTBOX_TENTATIVAS CHECK (TENTATIVAS >= 0)
);

CREATE INDEX IX_CP5_PAYMENT_OUTBOX_PENDING
    ON CP5_PAYMENT_OUTBOX (STATUS, CRIADO_EM);

CREATE SEQUENCE CP5_SEQ_EMAIL_NOTIFICATION
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE CP5_EMAIL_NOTIFICATION (
    ID BIGINT NOT NULL,
    COMPRA_ID BIGINT NOT NULL,
    DESTINATARIO VARCHAR(254),
    TIPO VARCHAR(40) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    TENTATIVAS INTEGER NOT NULL DEFAULT 0,
    CRIADO_EM TIMESTAMP WITH TIME ZONE NOT NULL,
    ULTIMA_TENTATIVA_EM TIMESTAMP WITH TIME ZONE,
    ENVIADO_EM TIMESTAMP WITH TIME ZONE,
    ULTIMO_ERRO VARCHAR(1000),
    CONSTRAINT PK_CP5_EMAIL_NOTIFICATION PRIMARY KEY (ID),
    CONSTRAINT FK_CP5_EMAIL_NOTIFICATION_COMPRA FOREIGN KEY (COMPRA_ID)
        REFERENCES CP5_COMPRA (ID) ON DELETE CASCADE,
    CONSTRAINT UK_CP5_EMAIL_NOTIFICATION_COMPRA_TIPO UNIQUE (COMPRA_ID, TIPO),
    CONSTRAINT CK_CP5_EMAIL_NOTIFICATION_TIPO CHECK (TIPO IN ('PAYMENT_APPROVED')),
    CONSTRAINT CK_CP5_EMAIL_NOTIFICATION_STATUS CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT CK_CP5_EMAIL_NOTIFICATION_TENTATIVAS CHECK (TENTATIVAS >= 0)
);

CREATE INDEX IX_CP5_EMAIL_NOTIFICATION_DELIVERY
    ON CP5_EMAIL_NOTIFICATION (STATUS, TENTATIVAS, CRIADO_EM);
