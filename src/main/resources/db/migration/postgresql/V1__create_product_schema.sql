CREATE SEQUENCE TDS_MVC_SEQ_MERCADO
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE TDS_MVC_TB_MERCADO (
    ID BIGINT NOT NULL,
    NOME VARCHAR(120) NOT NULL,
    TIPO VARCHAR(50) NOT NULL,
    SETOR VARCHAR(80) NOT NULL,
    TAMANHO VARCHAR(40) NOT NULL,
    PRECO NUMERIC(10, 2) NOT NULL,
    CONSTRAINT PK_TDS_MVC_TB_MERCADO PRIMARY KEY (ID),
    CONSTRAINT CK_TDS_MVC_MERCADO_PRECO_POSITIVO CHECK (PRECO > 0)
);
