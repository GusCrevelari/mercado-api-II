CREATE SEQUENCE CP5_SEQ_COMPRA
    START WITH 1
    INCREMENT BY 1;

CREATE SEQUENCE CP5_SEQ_COMPRA_ITEM
    START WITH 1
    INCREMENT BY 1;

CREATE TABLE CP5_COMPRA (
    ID BIGINT NOT NULL,
    USUARIO_ID BIGINT NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    TOTAL NUMERIC(14, 2) NOT NULL,
    CUSTO_TOTAL NUMERIC(14, 2) NOT NULL,
    MOEDA VARCHAR(3) NOT NULL,
    CORRELATION_ID UUID NOT NULL,
    CRIADO_EM TIMESTAMP WITH TIME ZONE NOT NULL,
    ATUALIZADO_EM TIMESTAMP WITH TIME ZONE NOT NULL,
    FINALIZADO_EM TIMESTAMP WITH TIME ZONE,
    VERSAO BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT PK_CP5_COMPRA PRIMARY KEY (ID),
    CONSTRAINT FK_CP5_COMPRA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES CP5_USUARIO (ID),
    CONSTRAINT UK_CP5_COMPRA_CORRELATION UNIQUE (CORRELATION_ID),
    CONSTRAINT CK_CP5_COMPRA_STATUS CHECK (STATUS IN ('PENDING_PAYMENT', 'APPROVED', 'REJECTED')),
    CONSTRAINT CK_CP5_COMPRA_TOTAL_POSITIVO CHECK (TOTAL > 0),
    CONSTRAINT CK_CP5_COMPRA_CUSTO_NAO_NEGATIVO CHECK (CUSTO_TOTAL >= 0),
    CONSTRAINT CK_CP5_COMPRA_MOEDA CHECK (CHAR_LENGTH(MOEDA) = 3)
);

CREATE TABLE CP5_COMPRA_ITEM (
    ID BIGINT NOT NULL,
    COMPRA_ID BIGINT NOT NULL,
    PRODUTO_ID BIGINT NOT NULL,
    PRODUTO_NOME VARCHAR(120) NOT NULL,
    QUANTIDADE INTEGER NOT NULL,
    PRECO_UNITARIO NUMERIC(10, 2) NOT NULL,
    CUSTO_UNITARIO NUMERIC(10, 2) NOT NULL,
    SUBTOTAL NUMERIC(14, 2) NOT NULL,
    SUBTOTAL_CUSTO NUMERIC(14, 2) NOT NULL,
    CONSTRAINT PK_CP5_COMPRA_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_CP5_COMPRA_ITEM_COMPRA FOREIGN KEY (COMPRA_ID) REFERENCES CP5_COMPRA (ID),
    CONSTRAINT FK_CP5_COMPRA_ITEM_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES TDS_MVC_TB_MERCADO (ID),
    CONSTRAINT UK_CP5_COMPRA_ITEM_PRODUTO UNIQUE (COMPRA_ID, PRODUTO_ID),
    CONSTRAINT CK_CP5_COMPRA_ITEM_QUANTIDADE_POSITIVA CHECK (QUANTIDADE > 0),
    CONSTRAINT CK_CP5_COMPRA_ITEM_PRECO_POSITIVO CHECK (PRECO_UNITARIO > 0),
    CONSTRAINT CK_CP5_COMPRA_ITEM_CUSTO_NAO_NEGATIVO CHECK (CUSTO_UNITARIO >= 0),
    CONSTRAINT CK_CP5_COMPRA_ITEM_SUBTOTAL_POSITIVO CHECK (SUBTOTAL > 0),
    CONSTRAINT CK_CP5_COMPRA_ITEM_SUBTOTAL_CUSTO_NAO_NEGATIVO CHECK (SUBTOTAL_CUSTO >= 0)
);

CREATE INDEX IX_CP5_COMPRA_USUARIO ON CP5_COMPRA (USUARIO_ID);
CREATE INDEX IX_CP5_COMPRA_STATUS ON CP5_COMPRA (STATUS);
CREATE INDEX IX_CP5_COMPRA_CRIADO_EM ON CP5_COMPRA (CRIADO_EM);
CREATE INDEX IX_CP5_COMPRA_ITEM_COMPRA ON CP5_COMPRA_ITEM (COMPRA_ID);
CREATE INDEX IX_CP5_COMPRA_ITEM_PRODUTO ON CP5_COMPRA_ITEM (PRODUTO_ID);
